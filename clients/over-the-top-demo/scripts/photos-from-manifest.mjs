#!/usr/bin/env node
/**
 * PHOTOS FROM THE MANIFEST
 *
 * `ott-demo-image-manifest.json` maps menu-item slugs to the photographs the
 * restaurant already serves from its own CDN. This script turns that mapping into
 * `data/photos.ts`, which `data/menu.ts` merges into every item.
 *
 *   node scripts/photos-from-manifest.mjs            # point at the CDN (default)
 *   node scripts/photos-from-manifest.mjs --local    # point at public/images/demo
 *
 * Remote mode is what the demo runs on today: the browser loads each photograph
 * straight from the restaurant's CDN, so the images are unambiguously theirs and
 * nothing is copied anywhere. Local mode is for production, once the owner has
 * handed over the assets — run `fetch-manifest-images.mjs` first, then this.
 *
 * Alt text comes from the restaurant's own menu descriptions, which are literal
 * ingredient lists and therefore honest. A slug with no description is reported
 * so a human writes it rather than the script inventing one.
 */

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, resolve } from "node:path";

const ROOT = resolve(import.meta.dirname, "..");
const MANIFEST = join(ROOT, "ott-demo-image-manifest.json");
const MENU = join(ROOT, "data", "menu.ts");
const OUT = join(ROOT, "data", "photos.ts");
const LOCAL_DIR = "/images/demo";

const local = process.argv.includes("--local");

/**
 * The hero runs full-bleed behind the headline, so it wants the loudest plate on
 * the menu rather than the first one in the file. Flaming Avalanche is the dish
 * Food Paradise filmed.
 */
const HERO_SLUG = "flaming-avalanche";

/** Every source is fetched `fit=contain`, so the dish is already whole and centred
 *  in its frame — a centred crop eats the padding before it ever reaches food.
 *  Override here only once someone has looked at the real photographs. */
const FOCAL = {};

/** Pull each item's id and description straight out of the menu data. */
function readMenu() {
  const source = readFileSync(MENU, "utf8");
  const body = source.slice(source.indexOf("export const menuItems"));
  const items = new Map();

  for (const m of body.matchAll(/\bB\(\s*"([a-z0-9-]+)"\s*,\s*"[^"]*"\s*,\s*\n?\s*"((?:[^"\\]|\\.)*)"/g)) {
    items.set(m[1], m[2]);
  }
  for (const m of body.matchAll(/\{\s*id:\s*"([a-z0-9-]+)"[\s\S]{0,400}?\}/g)) {
    const d = m[0].match(/description:\s*"((?:[^"\\]|\\.)*)"/);
    if (!items.has(m[1])) items.set(m[1], d ? d[1] : "");
  }
  return items;
}

function altFor(description) {
  if (!description) return null;
  const text = description.replace(/\\"/g, '"').replace(/\s+/g, " ").trim();
  const trimmed = text.length > 150 ? `${text.slice(0, 147).replace(/[\s,]+$/, "")}…` : text;
  return trimmed.replace(/\.$/, "");
}

const manifest = JSON.parse(readFileSync(MANIFEST, "utf8"));
const menu = readMenu();

const unknown = [];
const needsAlt = [];
const entries = [];
let hero = null;

for (const image of manifest.images) {
  const { slug, name, url } = image;

  if (!menu.has(slug)) {
    unknown.push(slug);
    continue;
  }

  const src = local ? `${LOCAL_DIR}/${slug}.jpg` : url;
  if (local && !existsSync(join(ROOT, "public", "images", "demo", `${slug}.jpg`))) {
    console.warn(`missing local file for ${slug} — run fetch-manifest-images.mjs first`);
  }

  const alt = altFor(menu.get(slug));
  if (!alt) needsAlt.push(slug);

  const entry = {
    src,
    alt: alt ?? `${name} as served at Over the Top Burger Bar. ALT TEXT NEEDED.`,
    focal: FOCAL[slug] ?? "50% 50%",
  };
  entries.push([slug, entry]);
  if (slug === HERO_SLUG) hero = entry;
}

const render = (e) =>
  [
    `    src: ${JSON.stringify(e.src)},`,
    `    alt: ${JSON.stringify(e.alt)},`,
    `    focal: "${e.focal}",`,
    `    credit: "Restaurant's own photography, served from their CDN",`,
  ].join("\n");

const body = entries
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([slug, e]) => `  "${slug}": {\n${render(e)}\n  },`)
  .join("\n");

writeFileSync(
  OUT,
  `/**
 * GENERATED by scripts/photos-from-manifest.mjs — do not hand-edit; re-run it.
 *
 * Photographs keyed by menu item id, sourced from ott-demo-image-manifest.json.
 * \`data/menu.ts\` merges this in, so a photo reaches every place its dish appears
 * without the menu data itself ever changing. An item with no entry here renders
 * the designed placeholder, which is most of the menu and is meant to be.
 *
 * Mode: ${local ? "local files under public/images/demo" : "the restaurant's own CDN"}
 */

import type { FoodImage } from "@/lib/types";

export const photos: Record<string, FoodImage> = {
${body}
};

/** The full-bleed photograph behind the homepage headline. */
export const heroPhoto: FoodImage | null = ${
    hero ? `{\n${render(hero)}\n}` : "null"
  };
`,
);

console.log(`Wrote ${entries.length} photographs to data/photos.ts (${local ? "local" : "CDN"} mode).`);
console.log(hero ? `Hero: ${HERO_SLUG}` : `Hero slug ${HERO_SLUG} not in manifest — hero left empty.`);
if (needsAlt.length) console.log(`Alt text needed (no menu description):\n  ${needsAlt.join("\n  ")}`);
if (unknown.length) console.log(`Slugs not found in data/menu.ts — skipped:\n  ${unknown.join("\n  ")}`);
